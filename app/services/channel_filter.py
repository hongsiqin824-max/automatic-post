def filter_blocked_channels(channels: Iterable[Any] | None) -> list[int]:
    """Return unique channel IDs after removing the exact blacklist matches."""

    if channels is None:
        return []
    result: list[int] = []
    seen: set[int] = set()
    for raw in channels:
        channel_id = int(raw)
        if channel_id in BLOCKED_CHANNEL_IDS or channel_id in seen:
            continue
        seen.add(channel_id)
        result.append(channel_id)
    return result
